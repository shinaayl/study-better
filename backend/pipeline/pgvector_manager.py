import os
import json
import logging
from typing import List, Dict, Any, Optional

logger = logging.getLogger(__name__)

class PgVectorManager:
    """
    Manages vector storage and semantic search using PostgreSQL + pgvector.
    Stores dense 768-dimensional embeddings generated by Google Gemini text-embedding-004.
    """
    def __init__(self, connection_url: Optional[str] = None):
        self.connection_url = connection_url or os.getenv("DATABASE_URL") or os.getenv("POSTGRES_URL")
        self._pool = None
        self._enabled = bool(self.connection_url)

    def is_available(self) -> bool:
        if not self._enabled:
            return False
        try:
            import psycopg2
            conn = psycopg2.connect(self.connection_url)
            conn.close()
            return True
        except Exception as e:
            logger.debug(f"pgvector database unavailable: {e}")
            return False

    def init_schema(self):
        """
        Executes schema migration to enable the vector extension and create the document_chunks_pgvector table.
        """
        if not self._enabled:
            return
        try:
            import psycopg2
            with psycopg2.connect(self.connection_url) as conn:
                with conn.cursor() as cur:
                    # 1. Enable extension
                    cur.execute("CREATE EXTENSION IF NOT EXISTS vector;")
                    # 2. Create chunks table
                    cur.execute("""
                    CREATE TABLE IF NOT EXISTS public.document_chunks_pgvector (
                        id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
                        course_id TEXT NOT NULL,
                        document_id TEXT NOT NULL,
                        document_title TEXT NOT NULL,
                        doc_type VARCHAR(64) NOT NULL,
                        page_number INTEGER NOT NULL,
                        chunk_index INTEGER NOT NULL,
                        chunk_text TEXT NOT NULL,
                        token_count INTEGER NOT NULL,
                        embedding vector(768),
                        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                    );
                    """)
                    # 3. Create indexes
                    cur.execute("""
                    CREATE INDEX IF NOT EXISTS idx_chunks_course_id ON public.document_chunks_pgvector(course_id);
                    CREATE INDEX IF NOT EXISTS idx_chunks_doc_type ON public.document_chunks_pgvector(doc_type);
                    CREATE INDEX IF NOT EXISTS idx_chunks_page_num ON public.document_chunks_pgvector(page_number);
                    """)
                conn.commit()
                logger.info("pgvector schema initialized successfully.")
        except Exception as e:
            logger.warning(f"pgvector init_schema skipped or failed: {e}")

    def insert_chunks(self, chunks: List[Dict[str, Any]]):
        """
        Inserts chunks and their 768-dim Gemini embeddings into PostgreSQL pgvector.
        Each chunk item should contain:
          - course_id
          - document_id
          - document_title
          - doc_type ('marking_scheme', 'past_question', 'lecture_note', 'handout')
          - page_number
          - chunk_index
          - chunk_text
          - token_count
          - embedding (List of 768 floats)
        """
        if not self._enabled or not chunks:
            return
        try:
            import psycopg2
            from psycopg2.extras import execute_values
            
            with psycopg2.connect(self.connection_url) as conn:
                with conn.cursor() as cur:
                    query = """
                    INSERT INTO public.document_chunks_pgvector 
                    (course_id, document_id, document_title, doc_type, page_number, chunk_index, chunk_text, token_count, embedding)
                    VALUES %s;
                    """
                    records = [
                        (
                            c["course_id"],
                            c["document_id"],
                            c["document_title"],
                            c["doc_type"],
                            c.get("page_number", 1),
                            c["chunk_index"],
                            c["chunk_text"],
                            c["token_count"],
                            f"[{','.join(str(v) for v in c['embedding'])}]" if c.get("embedding") else None
                        )
                        for c in chunks
                    ]
                    execute_values(cur, query, records)
                conn.commit()
                logger.info(f"Inserted {len(chunks)} chunks into PostgreSQL pgvector.")
        except Exception as e:
            logger.error(f"Failed to insert chunks into pgvector: {e}")

    def search(
        self,
        query_embedding: List[float],
        filter_course_id: Optional[str] = None,
        filter_doc_type: Optional[str] = None,
        top_k: int = 5
    ) -> List[Dict[str, Any]]:
        """
        Performs cosine distance nearest-neighbor vector search in PostgreSQL using the <=> operator.
        """
        if not self._enabled:
            return []
        try:
            import psycopg2
            with psycopg2.connect(self.connection_url) as conn:
                with conn.cursor() as cur:
                    emb_str = f"[{','.join(str(v) for v in query_embedding)}]"
                    query = """
                    SELECT
                        id, course_id, document_title, doc_type, page_number, chunk_index, chunk_text,
                        1 - (embedding <=> %s::vector) AS similarity
                    FROM public.document_chunks_pgvector
                    WHERE (%s IS NULL OR course_id = %s)
                      AND (%s IS NULL OR doc_type = %s)
                    ORDER BY embedding <=> %s::vector
                    LIMIT %s;
                    """
                    cur.execute(query, (
                        emb_str,
                        filter_course_id, filter_course_id,
                        filter_doc_type, filter_doc_type,
                        emb_str,
                        top_k
                    ))
                    rows = cur.fetchall()
                    results = []
                    for r in rows:
                        results.append({
                            "chunk_id": str(r[0]),
                            "course_id": r[1],
                            "document_title": r[2],
                            "doc_type": r[3],
                            "page_number": r[4],
                            "chunk_index": r[5],
                            "text": r[6],
                            "similarity": round(float(r[7]), 4) if r[7] is not None else 0.0
                        })
                    return results
        except Exception as e:
            logger.error(f"pgvector search error: {e}")
            return []

_instance: Optional[PgVectorManager] = None

def get_pgvector_manager() -> PgVectorManager:
    global _instance
    if _instance is None:
        _instance = PgVectorManager()
    return _instance
